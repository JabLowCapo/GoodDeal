export function makeKey(value) {
  if (typeof value !== 'string') return '';
  return value.normalize('NFKC').toLowerCase()
    .replace(/[أإآٱ]/gu, 'ا').replace(/ى/gu, 'ي')
    .replace(/[\s._'‘’ʼ\p{Pd}\u061C\u0640\u064B-\u0652\u0670\u200B-\u200F\u202A-\u202E\u2066-\u2069]/gu, '');
}

const canonicalByKey = new Map();
for (const labels of makeAliases) {
  const canonical = labels[0];
  for (const label of labels) {
    const key = makeKey(label);
    const existing = canonicalByKey.get(key);
    if (existing && existing !== canonical) {
      throw new Error(`Make alias "${label}" belongs to both ${existing} and ${canonical}`);
    }
    canonicalByKey.set(key, canonical);
  }
}

// These shorter labels identify a specific marque in the named marketplace's make selector.
// The Arabic spelling shared by JMC and GMC is intentionally absent.
const scopedAliases = new Map([
  ['autotraders', new Map([[makeKey('Avatar'), 'Avatr'], [makeKey('أفاتار'), 'Avatr']])],
  ['opensooq', new Map([[makeKey('Avatar'), 'Avatr'], [makeKey('أفاتار'), 'Avatr']])],
  ['carswitch', new Map([[makeKey('Galaxy'), 'Geely Galaxy'], [makeKey('جالكسي'), 'Geely Galaxy']])],
]);

export function chineseBrandForMake(make, marketplace) {
  const key = makeKey(make);
  return canonicalByKey.get(key) ?? scopedAliases.get(makeKey(marketplace))?.get(key) ?? null;
}
